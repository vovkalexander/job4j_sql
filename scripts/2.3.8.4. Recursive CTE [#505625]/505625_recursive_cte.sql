
-- построение дерева каталогов.
WITH RECURSIVE fold_tree AS (
    SELECT id,
          name,
	      parent_id,
          1 AS level,
	      name::text AS tree_path
	      FROM folders
          WHERE id = 1

          UNION ALL

	      SELECT f.id,
          f.name,
          f.parent_id,
	      ft.level + 1,
          ft.tree_path || ' -> ' || f.name
          FROM folders AS f
          JOIN fold_tree AS ft
          ON f.parent_id = ft.id
)
SELECT repeat('  -', level -1 ) || name AS folder_name,
       level
       from fold_tree
	   order by tree_path;

--  построение полного пути.
WITH RECURSIVE breadcrumb AS (
    SELECT id,
           name,
           parent_id,
           ARRAY[name] AS path
           FROM folders
           WHERE id = 10

           UNION ALL

           SELECT
               f.id,
               f.name,
               f.parent_id,
               f.name || b.path
               FROM folders AS f
               JOIN breadcrumb AS b
               ON f.id = b.parent_id
)
           SELECT  array_to_string(path, ' -> ') AS full_path
           FROM breadcrumb
           WHERE parent_id IS NULL;

--  защита от циклов.
WITH RECURSIVE fold_tree AS (
    SELECT id,
          name,
	      parent_id,
          1 AS level,
	      name::text AS tree_path
	      FROM folders
          WHERE id = 1

          UNION ALL

	      SELECT f.id,
          f.name,
          f.parent_id,
	      ft.level + 1,
          ft.tree_path || ' -> ' || f.name
          FROM folders AS f
          JOIN fold_tree AS ft
          ON f.parent_id = ft.id
)
  CYCLE id
   SET is_cycle
     USING cycle_path

SELECT repeat('  -', level -1 ) || name AS folder_name,
       level FROM fold_tree
       WHERE  is_cycle = false
	   ORDER BY tree_path;


CREATE TABLE folders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    parent_id BIGINT REFERENCES folders(id)
);

